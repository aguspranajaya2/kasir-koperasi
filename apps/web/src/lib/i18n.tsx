interface LanguageContextValue { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string }
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => localStorage.getItem("koperasi-language") === "en" ? "en" : "id");
  const setLanguage = (value: Language) => { localStorage.setItem("koperasi-language", value); setLanguageState(value); };
  const value = useMemo<LanguageContextValue>(() => ({ language, setLanguage, t: (text) => language === "en" ? translations[text] ?? text : text }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
